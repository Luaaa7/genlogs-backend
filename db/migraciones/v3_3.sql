BEGIN;

-- ----------------------------------------------------------------------------
-- 1. Fuentes de búsqueda (una fila por tienda)
--    activa : la enciende el Jefe Administrativo (solo si pasó la prueba de 10).
--    estado : resultado de "Probar sesión" (L1).
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fuente_busqueda (
    id_fuente           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo              VARCHAR(15)  NOT NULL,
    nombre              VARCHAR(60)  NOT NULL,
    url_base            VARCHAR(255) NOT NULL,
    activa              BOOLEAN      NOT NULL DEFAULT FALSE,
    estado              VARCHAR(25)  NOT NULL DEFAULT 'SIN_PROBAR',
    sesion_valida_hasta TIMESTAMP,
    ultima_prueba       TIMESTAMP,
    ultimo_error        VARCHAR(500),
    pausa_segundos      INTEGER      NOT NULL DEFAULT 5,
    limite_diario       INTEGER      NOT NULL DEFAULT 50,
    aciertos_prueba     SMALLINT,
    editado_por         BIGINT,
    user_create         VARCHAR(50)  NOT NULL,
    process_create      VARCHAR(100) NOT NULL,
    date_create         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update         VARCHAR(50),
    process_update      VARCHAR(100),
    date_update         TIMESTAMP,
    status              CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_fuente_busqueda PRIMARY KEY (id_fuente),
    CONSTRAINT uq_fuente_busqueda_codigo UNIQUE (codigo),
    CONSTRAINT ck_fuente_busqueda_codigo
        CHECK (codigo IN ('MERCADO_LIBRE', 'EBAY', 'AMAZON', 'ALIEXPRESS', 'ALIBABA')),
    CONSTRAINT ck_fuente_busqueda_estado
        CHECK (estado IN ('SIN_PROBAR', 'ACTIVA', 'CON_ERROR', 'REQUIERE_VERIFICACION')),
    CONSTRAINT ck_fuente_busqueda_pausa   CHECK (pausa_segundos >= 0),
    CONSTRAINT ck_fuente_busqueda_limite  CHECK (limite_diario > 0),
    CONSTRAINT ck_fuente_busqueda_aciertos
        CHECK (aciertos_prueba IS NULL OR aciertos_prueba BETWEEN 0 AND 10),
    CONSTRAINT ck_fuente_busqueda_status  CHECK (status IN ('A', 'I')),
    CONSTRAINT fk_fuente_busqueda_editor FOREIGN KEY (editado_por)
        REFERENCES public.usuario (id_usuario)
);

