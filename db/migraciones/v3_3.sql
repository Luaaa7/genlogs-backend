-- ----------------------------------------------------------------------------
-- 2. Credenciales de cada fuente, cifradas por el backend (K2, AES-GCM).
--    Nunca se devuelven por la API (L5): solo se escriben.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fuente_credencial (
    id_credencial  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_fuente      INTEGER      NOT NULL,
    tipo           VARCHAR(10)  NOT NULL,
    valor_cifrado  TEXT         NOT NULL,
    editado_por    BIGINT,
    user_create    VARCHAR(50)  NOT NULL,
    process_create VARCHAR(100) NOT NULL,
    date_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update    VARCHAR(50),
    process_update VARCHAR(100),
    date_update    TIMESTAMP,
    status         CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_fuente_credencial PRIMARY KEY (id_credencial),
    CONSTRAINT uq_fuente_credencial_tipo UNIQUE (id_fuente, tipo),
    CONSTRAINT ck_fuente_credencial_tipo CHECK (tipo IN ('USUARIO', 'CLAVE', 'SESION')),
    CONSTRAINT ck_fuente_credencial_status CHECK (status IN ('A', 'I')),
    CONSTRAINT fk_fuente_credencial_fuente FOREIGN KEY (id_fuente)
        REFERENCES public.fuente_busqueda (id_fuente) ON DELETE CASCADE,
    CONSTRAINT fk_fuente_credencial_editor FOREIGN KEY (editado_por)
        REFERENCES public.usuario (id_usuario)
);

-- ----------------------------------------------------------------------------
-- 3. Reglas de extracción por fuente, página y campo (M4 las edita, A4 las lee).
--    Las reglas por defecto las carga el dueño de cada lector (A1, A2, A3, M1).
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fuente_selector (
    id_selector    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_fuente      INTEGER      NOT NULL,
    pagina         VARCHAR(10)  NOT NULL,
    campo          VARCHAR(15)  NOT NULL,
    regla          TEXT         NOT NULL,
    editado_por    BIGINT,
    user_create    VARCHAR(50)  NOT NULL,
    process_create VARCHAR(100) NOT NULL,
    date_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update    VARCHAR(50),
    process_update VARCHAR(100),
    date_update    TIMESTAMP,
    status         CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_fuente_selector PRIMARY KEY (id_selector),
    CONSTRAINT uq_fuente_selector_campo UNIQUE (id_fuente, pagina, campo),
    CONSTRAINT ck_fuente_selector_pagina CHECK (pagina IN ('BUSQUEDA', 'FICHA')),
    CONSTRAINT ck_fuente_selector_campo
        CHECK (campo IN ('NOMBRE', 'DESCRIPCION', 'PRECIO', 'MONEDA', 'IMAGEN', 'ENLACE')),
    CONSTRAINT ck_fuente_selector_status CHECK (status IN ('A', 'I')),
    CONSTRAINT fk_fuente_selector_fuente FOREIGN KEY (id_fuente)
        REFERENCES public.fuente_busqueda (id_fuente) ON DELETE CASCADE,
    CONSTRAINT fk_fuente_selector_editor FOREIGN KEY (editado_por)
        REFERENCES public.usuario (id_usuario)
);

-- ----------------------------------------------------------------------------
-- 4. Historial de búsqueda: descripción, estado de la consulta y ALIEXPRESS
-- ----------------------------------------------------------------------------
ALTER TABLE public.historial_sourcing
    ADD COLUMN IF NOT EXISTS descripcion     TEXT,
    ADD COLUMN IF NOT EXISTS estado_consulta VARCHAR(20) NOT NULL DEFAULT 'OK';

-- Corrección: v3_2.sql dejó metodo en VARCHAR(10), pero su CHECK y el enum
-- MetodoBusqueda admiten 'NUMERO_PARTE' (12 letras). Guardar una búsqueda por
-- N.º de parte fallaba con "value too long". Ampliarla no pierde datos.
ALTER TABLE public.historial_sourcing ALTER COLUMN metodo TYPE VARCHAR(15);

ALTER TABLE public.historial_sourcing DROP CONSTRAINT IF EXISTS ck_historial_sourcing_estado_consulta;
ALTER TABLE public.historial_sourcing ADD CONSTRAINT ck_historial_sourcing_estado_consulta
    CHECK (estado_consulta IN ('OK', 'SIN_RESULTADOS', 'CON_ERROR', 'BLOQUEADA', 'MANUAL'));

-- v3_2.sql creó el CHECK de fuente sin nombre (PostgreSQL le puso uno propio,
-- p. ej. historial_sourcing_fuente_check). Se busca por su definición y se borra,
-- sin tocar los CHECK de metodo, estado ni origen.
DO $$
DECLARE
    restriccion RECORD;
BEGIN
    FOR restriccion IN
        SELECT conname
          FROM pg_constraint
         WHERE conrelid = 'public.historial_sourcing'::regclass
           AND contype = 'c'
           AND conname <> 'ck_historial_sourcing_fuente'
           AND pg_get_constraintdef(oid) LIKE '%(fuente)::text%'
    LOOP
        EXECUTE format('ALTER TABLE public.historial_sourcing DROP CONSTRAINT %I', restriccion.conname);
    END LOOP;
END $$;

ALTER TABLE public.historial_sourcing DROP CONSTRAINT IF EXISTS ck_historial_sourcing_fuente;
ALTER TABLE public.historial_sourcing ADD CONSTRAINT ck_historial_sourcing_fuente
    CHECK (fuente IN ('MERCADO_LIBRE', 'EBAY', 'AMAZON', 'ALIEXPRESS', 'ALIBABA', 'PROVEEDOR'));

