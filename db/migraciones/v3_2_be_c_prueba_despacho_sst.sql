BEGIN;

CREATE TABLE IF NOT EXISTS public.despacho (
    id_despacho        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_orden_compra    BIGINT       NOT NULL,
    id_cotizacion      BIGINT       NOT NULL,
    origen             VARCHAR(10)  NOT NULL,
    etapa              VARCHAR(20)  NOT NULL,
    fecha_preparacion  TIMESTAMP,
    fecha_aduana       TIMESTAMP,
    fecha_transito     TIMESTAMP,
    fecha_entrega      TIMESTAMP,
    plazo_desde        TIMESTAMP    NOT NULL,
    plazo_hasta        TIMESTAMP    NOT NULL,
    id_usuario         BIGINT       NOT NULL,
    user_create        VARCHAR(50)  NOT NULL,
    process_create     VARCHAR(100) NOT NULL,
    date_create        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update        VARCHAR(50),
    process_update     VARCHAR(100),
    date_update        TIMESTAMP,
    status             CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_despacho PRIMARY KEY (id_despacho),
    CONSTRAINT fk_despacho_orden FOREIGN KEY (id_orden_compra)
        REFERENCES public.orden_compra (id_orden_compra),
    CONSTRAINT fk_despacho_cotizacion FOREIGN KEY (id_cotizacion)
        REFERENCES public.cotizacion (id_cotizacion),
    CONSTRAINT fk_despacho_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario),
    CONSTRAINT ck_despacho_origen CHECK (origen IN ('NACIONAL', 'IMPORTADO')),
    CONSTRAINT ck_despacho_etapa CHECK (etapa IN (
        'REGISTRADO', 'EN_PREPARACION', 'EN_ADUANA', 'EN_TRANSITO', 'ENTREGADO')),
    CONSTRAINT ck_despacho_status CHECK (status IN ('A', 'I'))
);

CREATE TABLE IF NOT EXISTS public.despacho_sst (
    id_despacho_sst     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_despacho         BIGINT       NOT NULL,
    tipo                VARCHAR(10)  NOT NULL,
    fecha_emision       DATE,
    fecha_vencimiento   DATE         NOT NULL,
    url_documento       TEXT,
    referencia          VARCHAR(120),
    id_usuario          BIGINT       NOT NULL,
    fecha_confirmacion  TIMESTAMP    NOT NULL,
    user_create         VARCHAR(50)  NOT NULL,
    process_create      VARCHAR(100) NOT NULL,
    date_create         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update         VARCHAR(50),
    process_update      VARCHAR(100),
    date_update         TIMESTAMP,
    status              CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_despacho_sst PRIMARY KEY (id_despacho_sst),
    CONSTRAINT fk_despacho_sst_despacho FOREIGN KEY (id_despacho)
        REFERENCES public.despacho (id_despacho),
    CONSTRAINT fk_despacho_sst_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario),
    CONSTRAINT ck_despacho_sst_tipo CHECK (tipo IN ('PASE', 'SCTR')),
    CONSTRAINT ck_despacho_sst_status CHECK (status IN ('A', 'I'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_despacho_sst_activa
    ON public.despacho_sst (id_despacho, tipo) WHERE status = 'A';

-- Segunda vez, en la misma transacción.
CREATE TABLE IF NOT EXISTS public.despacho_sst (
    id_despacho_sst     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_despacho         BIGINT       NOT NULL,
    tipo                VARCHAR(10)  NOT NULL,
    fecha_emision       DATE,
    fecha_vencimiento   DATE         NOT NULL,
    url_documento       TEXT,
    referencia          VARCHAR(120),
    id_usuario          BIGINT       NOT NULL,
    fecha_confirmacion  TIMESTAMP    NOT NULL,
    user_create         VARCHAR(50)  NOT NULL,
    process_create      VARCHAR(100) NOT NULL,
    date_create         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_update         VARCHAR(50),
    process_update      VARCHAR(100),
    date_update         TIMESTAMP,
    status              CHAR(1)      NOT NULL DEFAULT 'A',
    CONSTRAINT pk_despacho_sst PRIMARY KEY (id_despacho_sst),
    CONSTRAINT fk_despacho_sst_despacho FOREIGN KEY (id_despacho)
        REFERENCES public.despacho (id_despacho),
    CONSTRAINT fk_despacho_sst_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario),
    CONSTRAINT ck_despacho_sst_tipo CHECK (tipo IN ('PASE', 'SCTR')),
    CONSTRAINT ck_despacho_sst_status CHECK (status IN ('A', 'I'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_despacho_sst_activa
    ON public.despacho_sst (id_despacho, tipo) WHERE status = 'A';

SELECT table_name, column_name, data_type, character_maximum_length, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name = 'despacho_sst'
ORDER BY ordinal_position;

SELECT indexname, indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND indexname = 'uq_despacho_sst_activa';

-- Segunda fila activa del mismo tipo debe fallar.
-- Pasar la anterior a I y volver a insertar debe dejar una sola activa.
-- Todo se deshace con el ROLLBACK de abajo.
DO $$
DECLARE
    v_oc bigint;
    v_cot bigint;
    v_usuario bigint;
    v_despacho bigint;
    v_activas int;
    v_vence date;
BEGIN
    SELECT id_orden_compra, id_cotizacion INTO v_oc, v_cot
      FROM public.orden_compra
     LIMIT 1;
    SELECT id_usuario INTO v_usuario
      FROM public.usuario
     LIMIT 1;

    IF v_oc IS NULL OR v_cot IS NULL OR v_usuario IS NULL THEN
        RAISE NOTICE 'Sin orden, cotización o usuario: no se inserta. El índice igual quedó creado.';
        RETURN;
    END IF;

    INSERT INTO public.despacho (
        id_orden_compra, id_cotizacion, origen, etapa,
        plazo_desde, plazo_hasta, id_usuario,
        user_create, process_create, status)
    VALUES (
        v_oc, v_cot, 'NACIONAL', 'EN_PREPARACION',
        CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, v_usuario,
        'PRUEBA', 'v3_2_be_c_prueba_despacho_sst', 'A')
    RETURNING id_despacho INTO v_despacho;

    INSERT INTO public.despacho_sst (
        id_despacho, tipo, fecha_vencimiento, referencia, id_usuario,
        fecha_confirmacion, user_create, process_create, status)
    VALUES (
        v_despacho, 'SCTR', DATE '2026-12-01', 'POL-1', v_usuario,
        CURRENT_TIMESTAMP, 'PRUEBA', 'v3_2_be_c_prueba_despacho_sst', 'A');

    BEGIN
        INSERT INTO public.despacho_sst (
            id_despacho, tipo, fecha_vencimiento, referencia, id_usuario,
            fecha_confirmacion, user_create, process_create, status)
        VALUES (
            v_despacho, 'SCTR', DATE '2026-12-15', 'POL-2', v_usuario,
            CURRENT_TIMESTAMP, 'PRUEBA', 'v3_2_be_c_prueba_despacho_sst', 'A');
        RAISE EXCEPTION 'La segunda fila activa del mismo tipo no fue rechazada';
    EXCEPTION
        WHEN unique_violation THEN
            RAISE NOTICE 'OK: la segunda fila activa de SCTR fue rechazada por uq_despacho_sst_activa';
    END;

    UPDATE public.despacho_sst
       SET status = 'I',
           user_update = 'PRUEBA',
           process_update = 'REEMPLAZO_SST',
           date_update = CURRENT_TIMESTAMP
     WHERE id_despacho = v_despacho
       AND tipo = 'SCTR'
       AND status = 'A';

    INSERT INTO public.despacho_sst (
        id_despacho, tipo, fecha_vencimiento, referencia, id_usuario,
        fecha_confirmacion, user_create, process_create, status)
    VALUES (
        v_despacho, 'SCTR', DATE '2027-01-20', 'POL-2', v_usuario,
        CURRENT_TIMESTAMP, 'PRUEBA', 'v3_2_be_c_prueba_despacho_sst', 'A')
    RETURNING fecha_vencimiento INTO v_vence;

    SELECT count(*) INTO v_activas
      FROM public.despacho_sst
     WHERE id_despacho = v_despacho
       AND tipo = 'SCTR'
       AND status = 'A';

    IF v_activas <> 1 OR v_vence <> DATE '2027-01-20' THEN
        RAISE EXCEPTION 'Tras corregir la fecha quedaron % activas y vence %', v_activas, v_vence;
    END IF;

    RAISE NOTICE 'OK: corregir la fecha deja 1 fila activa de SCTR, vence 2027-01-20';
END $$;

ROLLBACK;
